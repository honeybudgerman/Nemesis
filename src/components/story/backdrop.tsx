/** Pixel-art scene background, scaled to cover its box. */
export function StoryBackdrop({ kind, className, fit = "slice" }: { kind: Backdrop; className?: string; fit?: "slice" | "meet" }) {
  const s = SCENES[kind];
  return (
    <svg viewBox="0 0 64 36" preserveAspectRatio={`xMidYMid ${fit}`} shapeRendering="crispEdges" aria-hidden className={className}>
      {s.rects.map(([x, y, w, h, c], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} fill={c} />
      ))}
      {s.stars?.map(([x, y], i) => (
        <rect key={`s${i}`} x={x} y={y} width={1} height={1} fill="#fff1c4" className="anim-twinkle" style={{ animationDelay: `${(i % 5) * 0.4}s` }} />
      ))}
    </svg>
  );
}
